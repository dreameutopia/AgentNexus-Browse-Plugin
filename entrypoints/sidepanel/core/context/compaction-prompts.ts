/**
 * 压缩提示词的双策略配置（单一事实源，与 compactor 解耦）
 *
 * 两种压缩时机各自独立的策略与提示词（模块化边界）：
 *   - pre-run（发送前压缩，80% 触发）：跨轮次的会话级记忆——压缩对象是
 *     本轮之前的历史整体，产物将成为后续请求的唯一长期记忆，提示词按
 *     「会话记忆归档」口径：多轮意图演进、约束偏好、关键事实、进度与待办
 *     全量保真；
 *   - runtime（运行中压缩，90% 触发）：单次自治运行内的现场压缩——切分
 *     规划保留「最后一轮工具调用 + 其后续续拍消息」为尾部（见
 *     compaction-boundary），摘要只承载尾部之前的现场。提示词在相同分区
 *     结构之上**强化用户意图与阶段识别**：必须明确「用户需要什么」（最新
 *     诉求逐字保留）与「目前处于什么阶段」（当前工具循环、刚获得的证据、
 *     下一步动作），使模型压缩后能无缝续跑。
 *
 * 共享分区结构与差分压缩口径由 buildPartitionSections 生成，两份提示词
 * 只在开场定位段（本模块唯一的策略差异点）分叉——改分区结构一处生效，
 * 不会出现两份拷贝漂移。
 */

/** 压缩时机策略（compactor.compact 的 strategy 参数） */
export type CompactionStrategy = 'pre-run' | 'runtime';

/** 固定 XML 分区模板（两策略共享，见 compactor 头注释的分区契约） */
const PARTITION_TEMPLATE = `<summary>
  <task>当前核心目标：用户的核心任务与目标。逐条保留用户的原始诉求（关键表述保留原话）；多轮演进的意图变化写清先后关系与最新目标。</task>
  <constraints>用户明确的约束、偏好与规则（语言、格式、范围、禁止事项等）。</constraints>
  <key-facts>已确立的关键事实、数据、结论与决策。URL、文件名、笔记标题、页面标题、数字与单位等标识符必须原样保留。</key-facts>
  <progress>当前进度：已完成的工作与关键工具调用及其结果要点（做了什么、得到了什么、涉及哪些页面/站点），按推进顺序组织。</progress>
  <errors>错误经验：遇到的错误、失败原因与已尝试的处理；尚未解决的写明现状。失败尝试同样重要，必须记录以避免重复执行。</errors>
  <pending>待办与下一步：尚未完成的事项、用户等待中的结果与约定的下一步行动。任务计划（plan_tool）的执行状态存储在会话计划库中、不在本记录内，此处不得臆造计划状态。</pending>
</summary>`;

/** 差分压缩 / 防丢失 / 篇幅约束（两策略共享的压缩纪律） */
const COMPRESSION_DISCIPLINE = `3. 差分压缩（不同内容不同力度）：
   - 必须详尽保留：用户原话诉求、约束与偏好、关键事实与决策、错误及其原因、待办事项；
   - 大幅压缩：冗长的工具输出（页面全文抽取、DOM/观察结果、重复的探查与调试输出、长列表与重复样本）→ 归纳为结论与关键数据，标识符原样保留；
   - 可以丢弃：与任务无关的寒暄、重复表述、已被后续结果推翻的中间过程。

4. 防丢失硬性要求：
   - 用户消息的诉求一条都不能丢，关键表述保留原话；
   - 标识符（URL / 标题 / 笔记 ID / 工具名 / 数字与单位）原样保留，禁止改写或省略；
   - 只依据对话记录内容归纳，禁止臆造不存在的信息；
   - 在不丢失信息的前提下尽量精炼；信息与篇幅冲突时，保信息。

5. 篇幅约束：整个摘要一般控制在 4000 token 以内；信息确实庞大时可适当超出，但不得为凑短而丢弃任何用户诉求、关键事实、错误经验或待办。`;

/** 输出契约（两策略共享：单一 <summary> 元素、固定分区、XML 外无解释） */
const OUTPUT_CONTRACT = `输出要求（严格遵守）：
1. 只输出一个 <summary> XML 元素，XML 之外不得有任何解释文字。
2. 摘要体内依次包含以下固定分区（分区内容为空时写"无"，不得省略分区、不得改用其他标签名）：

${PARTITION_TEMPLATE}

`;

/**
 * 发送前压缩提示词（会话记忆归档口径）。
 * 压缩对象 = 本轮之前的历史整体；产物 = 该会话的长期记忆。
 */
export const COMPACTION_PROMPT_PRE_RUN = `你是「对话记忆压缩器」。你的唯一任务：把一段浏览器助手 AgentNexus 的对话历史（含工具调用与结果）压缩为结构化摘要，供同一对话的后续轮次作为记忆使用。摘要质量决定助手能否继续完成任务，因此信息完整性优先于简短。

${OUTPUT_CONTRACT}${COMPRESSION_DISCIPLINE}`;

/**
 * 运行中压缩提示词（现场压缩口径）。
 *
 * 与发送前的差异（策略分叉点）：
 *   1. 强化用户意图识别——本轮请求由用户的新诉求驱动，摘要必须让「用户
 *      需要什么」在压缩后依然逐字可辨（模型不能凭空重问用户已答过的问题）；
 *   2. 强化阶段识别——助手正处于任务推进的某个阶段（刚完成什么工具调用、
 *      拿到了什么证据、正要做什么），<progress> 必须写出这条现场主线；
 *   3. 声明记录边界——本记录只覆盖到此处为止的现场；更近的活动**若存在**
 *      （末轮体量在保留线以内时）由系统原样保留在摘要之后，若不存在（末轮
 *      体量过大一并被压缩）则以本记录截止处为准。两种情形都只要求「描述
 *      记录中实际出现的内容」，绝不臆造未出现的「最新活动」——
 *      措辞刻意不假定尾部形态：运行时切分有「末轮 ≤15% 保留」「末轮 >15%
 *      并入压缩」「纯对话以最后用户消息为界」三种可能（见
 *      compaction-boundary），提示词若假定某一种形态就会在另两种下误导
 *      压缩模型。
 */
export const COMPACTION_PROMPT_RUNTIME = `你是「对话记忆压缩器」，正在执行一次**运行中上下文压缩**：助手正处在任务执行现场，对话历史接近上下文上限，你负责把记录压缩为可无缝续跑的结构化摘要。摘要质量决定助手能否继续完成任务，因此信息完整性优先于简短。

与常规归档压缩不同，本次必须做到三点：
- **明确用户需要什么**：最新用户诉求逐字保留（原话不得改写），历史诉求的演进关系写清；模型压缩后必须能直接答出「用户到底要什么」，绝不允许把已明确的诉求压丢；
- **明确目前处于什么阶段**：<progress> 必须写出当前现场主线——正在执行什么任务阶段、最近一轮完成了什么工具调用、得到了什么关键证据、下一步准备做什么；
- **如实描述记录边界**：只写本记录中实际出现的内容；更近的活动若被系统原样保留在摘要之后，不要臆造它，也不要把它当作「记录里没做的事」。

${OUTPUT_CONTRACT}${COMPRESSION_DISCIPLINE}`;

/** 按策略取提示词（非法值回落 pre-run，防御性归一不抛错） */
export function compactionPromptFor(strategy?: CompactionStrategy): string {
  return strategy === 'runtime' ? COMPACTION_PROMPT_RUNTIME : COMPACTION_PROMPT_PRE_RUN;
}
