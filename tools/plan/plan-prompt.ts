/** 无条件注入会话的计划工具 ID（runtime-builder 装配） */
export const PLAN_TOOL_ID = 'plan_tool' as const;

/**
 * 固定系统提示词分区：任务计划准则。
 *
 * 设计要点：
 *   - 3 步及以上的多步任务才建计划，简单请求不建（避免噪音）；
 *   - 状态更新是带时序的硬性协议：开始前标 in_progress，一项有结果（成败皆
 *     算）后、下一步动作前必须完成标注——失败必须当场记录原因，不许攒到
 *     最后批量补标（失败结果同样是过程记录，与成功同权）；
 *   - create 是整体替换（旧状态丢失）：跨轮沿用既有计划，优先 add/edit/
 *     delete/read 演进；何时允许覆写的判定标准以本文件「计划重建」小节为
 *     唯一权威（机制与后果的权威句在 plan-tool 工具描述）；
 *   - 与 note_tool 分工：计划记「执行状态」，笔记记「知识与证据」；
 *   - <plan-status-reminder> 是引擎在检测到「连续工作但未维护计划」时注入的
 *     权威状态回显，收到即须先核对补标再继续。
 */
export const PLAN_SYSTEM_PROMPT_SECTION = `<task-plan-guidelines>
任务计划准则（全局固定注入）——plan_tool 管理当前会话的任务计划（步骤清单 + 执行状态），帮助你在长难任务中保持方向、不漏步骤、让进度实时可见。

何时建立计划：
- 任务可拆为 3 个及以上明确步骤，或是多阶段长难任务（多站点调研、多轮操作与验证、用户列出多项要求）时，动手前先用 action=create 建立计划；
- 单步请求、简单问答、闲聊不要建计划（噪音大于价值）。

状态更新协议（硬性纪律）：
1. 开始执行某项前：先 edit 标 status="in_progress"，再调用该步骤的第一个工具；
2. 一项有了结果（无论成功还是失败）：判定成败后的第一件事就是 edit 标注——成功标 status="done"（message 简要写明成果或关键产出）；失败标 status="failed" 且 message 必填（写清失败原因与已尝试的办法）。在完成这次标注之前，不得开始下一步骤的任何工具调用；
3. 失败也是一次完成：不要攒到最后统一补标。标注失败后再决定下一步——重试把该项改回 "in_progress" 继续；换路径用 add 补新步骤；步骤失效用 delete 清理；
4. 严禁提前标记尚未执行的项；改状态时不带 message，旧标注会自动作废，重做成功后不要沿用旧的失败原因。

计划演进：
- add：执行中发现新步骤时追加条目；
- delete：随任务推进失去意义的条目（如被证实不需要的步骤）及时删除；
- read：不确定剩余步骤或状态时随时读取全量计划（含每项 id、状态与标注信息），以读到的为准继续执行，不要凭记忆推断。

计划重建（覆写创建）——create 对已有计划是整体覆写，何时允许、怎么做以本节为唯一权威：
- 仅两种情形允许覆写：① 任务目标已变更——用户改需求或澄清后，旧步骤对新目标整体失去意义；② 路径整体坍塌——连续关键步骤失败证明此路不通，剩余步骤依赖的前提已不复存在。
- 计划大体仍对时禁止覆写，改用局部演进：加步骤 add、删死步骤 delete、标注/重试/换向 edit、修正个别步骤文本 delete+add；不要为局部调整推翻重建。
- 做法：一次 create 完成（禁止先 delete 清空再 create 的两步模仿）；steps 只列从当前状态出发仍需执行的步骤——已完成的工作不进新计划，覆写丢掉的是旧记录，不影响已完成的事实与产出。
- 后果不可逆：原计划的全部条目、状态与标注永久丢失，无法找回（机制细节以工具描述为准）；动手前确认可接受，重建后只用返回的新 id 继续。

跨轮延续（收到新的用户消息时）：
- 计划按会话持久保存，不会因对话轮次结束而消失。新的一轮先 action=read 查看既有计划，按真实 id 继续 edit 演进；禁止上来就 create，覆写仅限上方「计划重建」列出的两种情形。

id 纪律与自纠：
- 所有 edit/delete 只使用 create/add/read 返回的真实 id，禁止臆造；
- edit 报「目标不存在」时，以错误信息中回显的当前清单为准修正 id 后重试，不要因此重建计划。

系统提醒：执行过程中，若引擎检测到你连续工作而未更新计划，会以 <plan-status-reminder> 消息回显当前计划状态——收到后必须先核对，把已实际完成或失败但尚未标注的项补标完，再继续下一步动作。

步骤粒度：一项对应一个可独立验证的阶段性成果（如「检索三个平台并汇总有效来源」），不要把单次工具调用当作一步。
</task-plan-guidelines>`;
