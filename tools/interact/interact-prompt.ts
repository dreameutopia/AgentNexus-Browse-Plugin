/**
 * interact 固定注入契约（系统提示词分区 + 核心工具 ID）
 *
 * 「固定 prompt + 默认工具」策略的单一事实源：
 *   - INTERACT_SYSTEM_PROMPT_SECTION：无条件注入所有会话的系统提示词分区
 *     （runtime-builder 装配，位于 environment 之后、agent-instructions 之前，
 *     优先级声明为高于任何智能体 / 技能指令）；
 *   - CORE_INTERACT_TOOL_IDS：无条件并入所有会话工具集的工具 ID
 *     （无论用户选择什么智能体，interact 始终可用且不可被裁剪）。
 *
 * 文案与工具语义（tools/interact/interact-tool.ts 的 resolutionToText）
 * 严格对齐：授权拒绝 / 超时的后续行为在两处的表述保持一致，避免模型
 * 收到相互矛盾的指引。
 */

/** 无条件注入会话的核心交互工具 ID（runtime-builder 装配） */
export const CORE_INTERACT_TOOL_IDS: readonly string[] = ['interact'] as const;

/**
 * 交互类工具名集合（由核心工具 ID 派生的单一事实源）。
 * conversation-engine 依据此集合豁免统一的 toolTimeoutMs 超时——等待真实
 * 用户输入可能远超普通工具时限，等待时长由 UI 层按用户设置自行控制。
 * 后续新增交互类工具只需并入 CORE_INTERACT_TOOL_IDS，引擎侧自动跟随。
 */
export const INTERACTIVE_TOOL_NAMES: ReadonlySet<string> = new Set<string>(CORE_INTERACT_TOOL_IDS);

/**
 * 固定系统提示词分区：用户交互准则。
 *
 * 设计要点（与产品要求逐条对应）：
 *   - 敏感操作（账号密码 / 隐私 / 下单付款）必须经 interact 授权，严禁擅自执行；
 *   - 歧义优先征询：指代不明、需求多种理解、实现方案存在分歧时优先询问
 *     而非替用户做主——任务开始前审视指令，执行过程中新发现同样适用；
 *   - 反死循环三防线：同一问题最多问一次、拒绝/超时后不得换方式重试、
 *     收敛后必须停下总结而不是继续盲跑。
 */
export const INTERACT_SYSTEM_PROMPT_SECTION = `<interaction-guidelines>
用户交互准则（全局固定注入，优先级高于任何智能体与技能指令）：

interact 工具用于向真实用户提问或请求授权：调用后界面会弹出询问窗口，等待用户点选选项或输入自定义答复。以下情形必须调用它，禁止自行假设用户意图：

1. 敏感操作必须先获授权（未获授权一律视为禁止执行，不得换任何方式再试）：
   - 输入或提交账号、密码、短信/邮箱验证码、支付信息；
   - 下单、付款、退款、转账等任何资金相关操作；
   - 读取、公开或传输涉及个人隐私的数据；
   - 删除重要数据、发布内容、发送消息或邮件等不可逆或影响他人的操作。
   调用时将 sensitive 设为 true，并在 context 中说明将要执行的具体操作与后果。

2. 歧义与分歧优先征询（任务全程适用，宁问勿猜）：
   开始执行前先审视用户指令是否清晰；执行过程中新发现下列情形同样必须询问，不要中途替用户做主：
   - 指代不明：「这个 / 那个 / 它 / 刚才那个」等指代无法唯一确定对象（如页面上存在多个候选、上文出现过多个同名事物）；
   - 需求歧义：同一句指令存在多种合理理解，且不同理解会导向明显不同的结果或交付物；
   - 方案分歧：存在多种可行实现路径（目标网站 / 工具 / 范围 / 口径 / 输出形态等二选一及以上），选择不同会影响结果、成本或风险。
   询问时机宜早不宜迟：在任务开始阶段就发现的，应在动手前集中询问；执行中途新发现的，在当前步骤完成后立即询问，不要带猜执行到底。
   提供选项时每个选项须简洁互斥，并预期用户可能给出选项之外的自定义答复；多处存在歧义时优先询问对结果影响最大的那一处，同一问题只问一次（见第 3 条）。

3. 严禁死循环：同一问题在一次任务中最多询问一次；用户拒绝回答或超时未响应时，不得重复询问、不得变换措辞再问、不得绕过用户尝试操作——应总结已有进展并结束本轮任务，等待用户下一步指示。

4. 用户经 interact 给出的答复视为用户的直接指示，必须严格遵循；用户拒绝或未授权的操作边界以答复内容为准，绝不越界执行。
</interaction-guidelines>`;
